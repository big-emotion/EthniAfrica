#!/usr/bin/env npx tsx
/**
 * Name-history coverage per folder, and the order of the long tail (ETNI-2011).
 *
 *   npx tsx scripts/afrik/nameHistoryWaveOrder.ts            coverage + wave summary
 *   npx tsx scripts/afrik/nameHistoryWaveOrder.ts --list     the full list, as a document
 *   npx tsx scripts/afrik/nameHistoryWaveOrder.ts --first-wave=20
 *
 * Run in every wave pull request: the coverage table is the number of
 * subjects with a complete nameHistory, per folder. It reads the corpus in
 * git and a committed visits snapshot, so it needs no credentials and gives
 * the same answer on every machine.
 */

import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import {
  cutWaves,
  nameHistoryCoverage,
  orderTail,
  readTail,
  renderWaveList,
  renderWaveSummary,
} from "../lib/nameHistoryWaveOrder";

const CORPUS = resolve(process.cwd(), "dataset/source/afrik");
const VISITS = resolve(
  process.cwd(),
  "scripts/data/ficheVisits-2026-10-12.json"
);
const DEFAULT_FIRST_WAVE = 14;

const firstWaveArg = process.argv.find((arg) =>
  arg.startsWith("--first-wave=")
);
const firstWave = firstWaveArg
  ? Number(firstWaveArg.split("=")[1])
  : DEFAULT_FIRST_WAVE;

const snapshot = JSON.parse(readFileSync(VISITS, "utf8")) as {
  window: { from: string; to: string };
  visitors: Record<string, number>;
};

const tail = orderTail(readTail(CORPUS, snapshot.visitors));
const waves = cutWaves(
  tail.filter((subject) => subject.kind === "people"),
  tail.filter((subject) => subject.kind === "family-name"),
  firstWave
);

const coverageTable = [
  "| Folder | Fiches | Complete nameHistory | Without |",
  "| ------ | -----: | -------------------: | ------: |",
  ...nameHistoryCoverage(CORPUS).map(
    ({ folder, fiches, complete }) =>
      `| \`${folder}\` | ${fiches} | ${complete} | ${fiches - complete} |`
  ),
].join("\n");

if (process.argv.includes("--list")) {
  console.log(`---
title: "Name history: the long tail, wave by wave"
status: "generated; see name-history-priority-core.md for the method"
related:
  - docs/editorial/strategy/name-history-priority-core.md
---

# Name history: the long tail, wave by wave

Generated by \`npx tsx scripts/afrik/nameHistoryWaveOrder.ts --list\`. Demand
window: ${snapshot.window.from} to ${snapshot.window.to}. Regenerate it at the
start of each wave: finished subjects leave the list and the rest moves up.

${renderWaveList(waves)}
`);
} else {
  console.log(`## Coverage\n\n${coverageTable}\n`);
  console.log(`## Waves from ${firstWave}\n\n${renderWaveSummary(waves)}`);
}
